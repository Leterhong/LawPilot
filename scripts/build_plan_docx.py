def build() -> None:
    if not TEMPLATE.exists():
        raise SystemExit(f"模板缺失：{TEMPLATE}")
    with zipfile.ZipFile(TEMPLATE) as z:
        ref_doc = z.read("word/document.xml").decode("utf-8")
        head = ref_doc[: ref_doc.index("<w:body>") + len("<w:body>")]
        sect = ref_doc[ref_doc.rindex("<w:sectPr"):]
        sect = sect[: sect.index("</w:sectPr>") + len("</w:sectPr>")]
        new_doc = f"{head}{''.join(BLOCKS)}{sect}</w:body></w:document>"

        header = z.read("word/header1.xml").decode("utf-8")
        header = re.sub(r"<w:t[^>]*>[^<]*</w:t>", f'<w:t xml:space="preserve">{HEADER_TEXT}</w:t>', header, count=1)
        footer = z.read("word/footer1.xml").decode("utf-8")
        footer = re.sub(r"<w:t[^>]*>[^<]*</w:t>", f'<w:t xml:space="preserve">{FOOTER_TEXT}</w:t>', footer, count=1)
        core = z.read("docProps/core.xml").decode("utf-8")
        core = re.sub(r"<dc:title>[^<]*</dc:title>", "<dc:title>明路 项目计划书</dc:title>", core)

        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        tmp = OUTPUT.with_suffix(".tmp.docx")
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as out:
            for item in z.infolist():
                if item.filename == "word/document.xml":
                    out.writestr(item, new_doc.encode("utf-8"))
                elif item.filename == "word/header1.xml":
                    out.writestr(item, header.encode("utf-8"))
                elif item.filename == "word/footer1.xml":
                    out.writestr(item, footer.encode("utf-8"))
                elif item.filename == "docProps/core.xml":
                    out.writestr(item, core.encode("utf-8"))
                else:
                    out.writestr(item, z.read(item.filename))
    shutil.move(str(tmp), str(OUTPUT))
    words = sum(len(b) for b in BLOCKS)
    print(f"OK -> {OUTPUT}")
    print(f"blocks={len(BLOCKS)} chars≈{words}")


if __name__ == "__main__":
    build()
