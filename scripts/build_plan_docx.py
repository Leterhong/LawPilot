def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def run(text: str, bold: bool = False, size: int = 21) -> str:
    b = "<w:b/>" if bold else '<w:b w:val="0"/>'
    return (
        f'<w:r><w:rPr>{b}<w:color w:val="000000"/><w:sz w:val="{size}"/></w:rPr>'
        f'<w:t xml:space="preserve">{esc(text)}</w:t></w:r>'
    )


def p(text: str, style: str | None = None, page_break: bool = False) -> str:
    props = ""
    if style or page_break:
        props = "<w:pPr>"
        if style:
            props += f'<w:pStyle w:val="{style}"/>'
        if page_break:
            props += "<w:pageBreakBefore/>"
        props += "</w:pPr>"
    return f"<w:p>{props}<w:r><w:t xml:space=\"preserve\">{esc(text)}</w:t></w:r></w:p>"


def spacer() -> str:
    return '<w:p><w:pPr><w:spacing w:after="0" w:line="80" w:lineRule="exact"/></w:pPr></w:p>'


def cell(text: str, width: int, fill: str, center: bool, bold: bool) -> str:
    jc = '<w:jc w:val="center"/>' if center else ""
    return (
        "<w:tc><w:tcPr>"
        f'<w:tcW w:w="{width}" w:type="dxa"/>'
        f'<w:shd w:val="clear" w:color="auto" w:fill="{fill}"/>'
        '<w:tcMar><w:top w:w="95" w:type="dxa"/><w:left w:w="95" w:type="dxa"/>'
        '<w:bottom w:w="95" w:type="dxa"/><w:right w:w="95" w:type="dxa"/></w:tcMar>'
        '<w:vAlign w:val="center"/></w:tcPr>'
        f'<w:p><w:pPr><w:spacing w:after="40" w:line="310" w:lineRule="exact"/>{jc}</w:pPr>'
        f"{run(text, bold=bold)}</w:p></w:tc>"
    )


def table(grid: list[int], header: list[str], rows: list[list[str]]) -> str:
    out = [
        "<w:tbl><w:tblPr>",
        '<w:tblStyle w:val="32"/><w:tblW w:w="0" w:type="auto"/><w:jc w:val="center"/>',
        BORDER,
        '<w:tblLayout w:type="fixed"/>',
        CELL_MAR,
        "</w:tblPr><w:tblGrid>",
        "".join(f'<w:gridCol w:w="{w}"/>' for w in grid),
        "</w:tblGrid>",
    ]
    # 表头
    out.append(f"<w:tr>{TBL_PREX}")
    out.append('<w:trPr><w:cantSplit/><w:tblHeader/><w:jc w:val="center"/></w:trPr>')
    for w, text in zip(grid, header):
        out.append(cell(text, w, "E8EDF1", center=True, bold=True))
    out.append("</w:tr>")
    # 数据行
    for row in rows:
        out.append(f"<w:tr>{TBL_PREX}<w:trPr><w:cantSplit/></w:trPr>")
        for i, (w, text) in enumerate(zip(grid, row)):
            out.append(cell(text, w, "FFFFFF", center=(i == 0), bold=False))
        out.append("</w:tr>")
    out.append("</w:tbl>")
    out.append(spacer())
    return "".join(out)


